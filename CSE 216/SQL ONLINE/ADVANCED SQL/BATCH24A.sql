SELECT E.EMPLOYEE_ID, E.FIRST_NAME || ' ' || E.LAST_NAME, D.DEPARTMENT_NAME, E.SALARY, J.JOB_TITLE
FROM EMPLOYEES E 
JOIN DEPARTMENTS D 
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN JOBS J
ON E.JOB_ID = J.JOB_ID
WHERE E.SALARY = 
(
  SELECT MAX(E1.SALARY)
  FROM EMPLOYEES E1
  WHERE E.DEPARTMENT_ID = E1.DEPARTMENT_ID AND
    E1.SALARY < (
        SELECT MAX(E2.SALARY)
        FROM EMPLOYEES E2
        WHERE E.DEPARTMENT_ID = E2.DEPARTMENT_ID
      )
)

AND E.DEPARTMENT_ID IN 
(
  SELECT DEPARTMENT_ID 
  FROM EMPLOYEES 
  GROUP BY DEPARTMENT_ID 
  HAVING COUNT(EMPLOYEE_ID) >= 2
)
ORDER BY DEPARTMENT_NAME ASC,
          SALARY DESC


