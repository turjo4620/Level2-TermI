SELECT LAST_NAME, SALARY, (
SELECT DEPARTMENT_NAME
FROM DEPARTMENTS D 
WHERE E1.DEPARTMENT_ID = D.DEPARTMENT_ID
) "DEPARTMENT_NAME"
FROM EMPLOYEES E1
WHERE SALARY > (
    SELECT AVG(SALARY)
    FROM EMPLOYEES E2
    WHERE E1.DEPARTMENT_ID = E2.DEPARTMENT_ID
)


