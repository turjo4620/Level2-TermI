CREATE TABLE employees_copy AS
SELECT * FROM employees;
COMMIT;


CREATE OR REPLACE FUNCTION EXCHANGE_EMPLOYEES (
    MANAGER_ID1 IN EMPLOYEES.MANAGER_ID%TYPE,
    MANAGER_ID2 IN EMPLOYEES.MANAGER_ID%TYPE
)
RETURN VARCHAR2
IS
    -- variables
    V_EMP1 EMPLOYEES.EMPLOYEE_ID%TYPE;
    V_SALARY1 EMPLOYEES.SALARY%TYPE;
    V_MANAGER1 EMPLOYEES.MANAGER_ID%TYPE;
    V_DEPT1 EMPLOYEES.DEPARTMENT_ID%TYPE;
    V_EMP2 EMPLOYEES.EMPLOYEE_ID%TYPE;
    V_SALARY2 EMPLOYEES.SALARY%TYPE;
    V_MANAGER2 EMPLOYEES.MANAGER_ID%TYPE; 
    V_DEPT2 EMPLOYEES.DEPARTMENT_ID%TYPE;
    V_DIFF EMPLOYEES.SALARY%TYPE;
    V_NEW_SALARY1 EMPLOYEES.SALARY%TYPE;
    V_NEW_SALARY2 EMPLOYEES.SALARY%TYPE;

BEGIN

    SELECT EMPLOYEE_ID, SALARY, MANAGER_ID, DEPARTMENT_ID
    INTO V_EMP1, V_SALARY1, V_MANAGER1, V_DEPT1
    FROM EMPLOYEES_COPY
    WHERE MANAGER_ID = MANAGER_ID1
    ORDER BY SALARY
    FETCH FIRST 1 ROW ONLY;

    SELECT EMPLOYEE_ID, SALARY, MANAGER_ID, DEPARTMENT_ID
    INTO V_EMP2, V_SALARY2, V_MANAGER2, V_DEPT2
    FROM EMPLOYEES_COPY
    WHERE MANAGER_ID = MANAGER_ID2
    ORDER BY SALARY
    FETCH FIRST 1 ROW ONLY;
    
    V_DIFF := ABS(V_SALARY1 - V_SALARY2);
    
    V_NEW_SALARY1 := V_SALARY1 + 0.5 * V_DIFF;

    V_NEW_SALARY2 := V_SALARY2 + 0.5 * V_DIFF;
    
    
        DBMS_OUTPUT.PUT_LINE('========== BEFORE EXCHANGE ==========');

    DBMS_OUTPUT.PUT_LINE('Employee Information:');
    DBMS_OUTPUT.PUT_LINE('Employee ID: ' || V_EMP1);
    DBMS_OUTPUT.PUT_LINE('Salary: ' || V_SALARY1);
    DBMS_OUTPUT.PUT_LINE('Manager ID: ' || V_MANAGER1);
    DBMS_OUTPUT.PUT_LINE('Department ID: ' || V_DEPT1);

    DBMS_OUTPUT.PUT_LINE('-------------------------------------');

    DBMS_OUTPUT.PUT_LINE('Employee Information:');
    DBMS_OUTPUT.PUT_LINE('Employee ID: ' || V_EMP2);
    DBMS_OUTPUT.PUT_LINE('Salary: ' || V_SALARY2);
    DBMS_OUTPUT.PUT_LINE('Manager ID: ' || V_MANAGER2);
    DBMS_OUTPUT.PUT_LINE('Department ID: ' || V_DEPT2);
    
    UPDATE EMPLOYEES_COPY
    SET MANAGER_ID = V_MANAGER2,
    DEPARTMENT_ID = V_DEPT2,
    SALARY = V_NEW_SALARY1
    WHERE EMPLOYEE_ID = V_EMP1;
    
    UPDATE EMPLOYEES_COPY
    SET MANAGER_ID = V_MANAGER1,
    DEPARTMENT_ID = V_DEPT1,
    SALARY = V_NEW_SALARY2
    WHERE EMPLOYEE_ID = V_EMP2; 
    
    
    DBMS_OUTPUT.PUT_LINE('========== AFTER EXCHANGE ==========');

    DBMS_OUTPUT.PUT_LINE('Employee Information:');
    DBMS_OUTPUT.PUT_LINE('Employee ID: ' || V_EMP1);
    DBMS_OUTPUT.PUT_LINE('Salary: ' || V_NEW_SALARY1);
    DBMS_OUTPUT.PUT_LINE('Manager ID: ' || V_MANAGER2);
    DBMS_OUTPUT.PUT_LINE('Department ID: ' || V_DEPT2);

    DBMS_OUTPUT.PUT_LINE('-------------------------------------');

    DBMS_OUTPUT.PUT_LINE('Employee Information:');
    DBMS_OUTPUT.PUT_LINE('Employee ID: ' || V_EMP2);
    DBMS_OUTPUT.PUT_LINE('Salary: ' || V_NEW_SALARY2);
    DBMS_OUTPUT.PUT_LINE('Manager ID: ' || V_MANAGER1);
    DBMS_OUTPUT.PUT_LINE('Department ID: ' || V_DEPT1);


    COMMIT;

    RETURN 'SUCCESS';
    

EXCEPTION

    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('No data found.');
        RETURN 'FAILED';

    WHEN TOO_MANY_ROWS THEN
        DBMS_OUTPUT.PUT_LINE('Too many rows.');
        RETURN 'FAILED';

    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('Error: ' || SQLERRM);
        RETURN 'FAILED';
END;
/

