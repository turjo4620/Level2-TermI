CREATE TABLE MANAGER_SUMMARY (
MANAGER_ID NUMBER,
DEPARTMENT_ID NUMBER,
MANAGER_NAME VARCHAR2(100),
DIRECT_REPORT_COUNT NUMBER,
GENERATED_BY VARCHAR2(30),
GENERATED_ON DATE
);

-- SQL FUNCTION

CREATE OR REPLACE FUNCTION GET_DIRECT_REPORT_COUNT (
P_EMP_ID IN NUMBER
) RETURN NUMBER IS NUM_EM NUMBER;
BEGIN
  SELECT COUNT(EMPLOYEE_ID)
  INTO NUM_EM
  FROM EMPLOYEES
  WHERE MANAGER_ID = P_EMP_id;
  RETURN NUM_EM;
END;

-- PROCEDURE

CREATE OR REPLACE PROCEDURE BUILD_MANAGER_SUMMARY (
P_DEPT_ID IN NUMBER,
P_MANAGER_COUNT OUT NUMBER,
P_TOTAL_REPORTS OUT NUMBER
)

IS EMPLOYEE_FOUND NUMBER := 0;

BEGIN 

  P_MANAGER_COUNT := 0;
  P_TOTAL_REPORTS := 0;

  DELETE FROM MANAGER_SUMMARY
  WHERE DEPARTMENT_ID =  P_DEPT_ID;
  
  FOR EMPLOYEE_RECORD IN(
    SELECT EMPLOYEE_ID, 
    DEPARTMENT_ID, 
    FIRST_NAME || ' ' || LAST_NAME FULL_NAME,
    GET_DIRECT_REPORT_COUNT(EMPLOYEE_ID) REPORT_COUNT
    
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID = P_DEPT_ID
  )
  
  LOOP
    EMPLOYEE_FOUND := 1;
    IF EMPLOYEE_RECORD.REPORT_COUNT > 0 THEN
    P_MANAGER_COUNT := P_MANAGER_COUNT + 1;
    P_TOTAL_REPORTS := P_TOTAL_REPORTS + EMPLOYEE_RECORD.REPORT_COUNT;
    INSERT INTO MANAGER_SUMMARY
    VALUES(EMPLOYEE_RECORD.EMPLOYEE_ID, EMPLOYEE_RECORD.DEPARTMENT_ID, EMPLOYEE_RECORD.FULL_NAME, EMPLOYEE_RECORD.REPORT_COUNT, USER, SYSDATE);
    END IF;
  
  END LOOP;
  
      IF EMPLOYEE_RECORD.REPORT_COUNT  = 0 THEN
    DBMS_OUTPUT.PUT_LINE(
        'No employees in department ' || P_DEPT_ID
    );
  END IF;
END;
/

DECLARE
  V_MANAGER_COUNT NUMBER;
  V_TOTAL_REPORTS NUMBER;
  BEGIN
    BUILD_MANAGER_SUMMARY(
      50,
      V_MANAGER_COUNT,
      V_TOTAL_REPORTS
      );
      
DBMS_OUTPUT.PUT_LINE(
    'Manager Count: ' || V_MANAGER_COUNT
);

DBMS_OUTPUT.PUT_LINE(
    'Total Reports: ' || V_TOTAL_REPORTS
);
  END;
