CREATE TABLE DEPT_RELOCATION_LOG (
DEPARTMENT_ID NUMBER,
OLD_LOCATION_ID NUMBER,
NEW_LOCATION_ID NUMBER,
OLD_CITY VARCHAR2(30),
NEW_CITY VARCHAR2(30),
RELOCATION_TYPE VARCHAR2(15),
RAISE_PCT NUMBER,
EMPLOYEES_AFFECTED NUMBER,
CHANGED_BY VARCHAR2(30),
CHANGED_ON DATE
);



CREATE OR REPLACE TRIGGER DEPT_RELOCATION
AFTER UPDATE OF LOCATION_ID ON DEPARTMENTS
FOR EACH ROW

DECLARE

    V_OLD_CITY      LOCATIONS.CITY%TYPE;
    V_NEW_CITY      LOCATIONS.CITY%TYPE;

    V_OLD_COUNTRY   LOCATIONS.COUNTRY_ID%TYPE;
    V_NEW_COUNTRY   LOCATIONS.COUNTRY_ID%TYPE;

    V_OLD_REGION    COUNTRIES.REGION_ID%TYPE;
    V_NEW_REGION    COUNTRIES.REGION_ID%TYPE;

    V_EMPLOYEES_AFFECTED NUMBER;
    V_RAISE_PCT          NUMBER;
    V_RELOCATION_TYPE    VARCHAR2(15);

BEGIN
  IF :OLD.LOCATION_ID <> :NEW.LOCATION_ID THEN
    SELECT L.CITY,
       L.COUNTRY_ID,
       C.REGION_ID
    INTO V_OLD_CITY,
       V_OLD_COUNTRY,
       V_OLD_REGION
    FROM LOCATIONS L
    JOIN COUNTRIES C
    ON L.COUNTRY_ID = C.COUNTRY_ID  
    WHERE L.LOCATION_ID = :OLD.LOCATION_ID;
    
     SELECT L.CITY,
       L.COUNTRY_ID,
       C.REGION_ID
    INTO V_NEW_CITY,
       V_NEW_COUNTRY,
       V_NEW_REGION
    FROM LOCATIONS L
    JOIN COUNTRIES C
    ON L.COUNTRY_ID = C.COUNTRY_ID  
    WHERE L.LOCATION_ID = :NEW.LOCATION_ID;
    
    
IF V_OLD_COUNTRY = V_NEW_COUNTRY THEN

    V_RELOCATION_TYPE := 'DOMESTIC';
    V_RAISE_PCT := 3;

ELSIF V_OLD_REGION = V_NEW_REGION THEN

    V_RELOCATION_TYPE := 'REGIONAL';
    V_RAISE_PCT := 8;

ELSE

    V_RELOCATION_TYPE := 'OVERSEAS';
    V_RAISE_PCT := 12;

END IF;

SELECT COUNT(*) 
INTO V_EMPLOYEES_AFFECTED
FROM EMPLOYEES
WHERE DEPARTMENT_ID = :OLD.DEPARTMENT_ID;

UPDATE EMPLOYEES
SET SALARY = ROUND(SALARY * (100 + V_RAISE_PCT) / 100, 2)
WHERE DEPARTMENT_ID = :OLD.DEPARTMENT_ID;




INSERT INTO DEPT_RELOCATION_LOG (
    DEPARTMENT_ID,
    OLD_LOCATION_ID,
    NEW_LOCATION_ID,
    OLD_CITY,
    NEW_CITY,
    RELOCATION_TYPE,
    RAISE_PCT,
    EMPLOYEES_AFFECTED,
    CHANGED_BY,
    CHANGED_ON
)
VALUES (
    :OLD.DEPARTMENT_ID,
    :OLD.LOCATION_ID,
    :NEW.LOCATION_ID,
    V_OLD_CITY,
    V_NEW_CITY,
    V_RELOCATION_TYPE,
    V_RAISE_PCT,
    V_EMPLOYEES_AFFECTED,
    USER,
    SYSDATE
);
END IF;
END;
